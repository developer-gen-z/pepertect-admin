/**
 * Look up the Upstox instrument_key for a given symbol.
 * Returns the instrument_key, or null if not found.
 */
export function getUpstoxKey(symbol: string): string | null {
  if (!symbol) return null;
  const s = symbol.toUpperCase().trim();
  if (INDEX_TO_UPSTOX_KEY[s]) return INDEX_TO_UPSTOX_KEY[s];
  if (STOCK_TO_UPSTOX_KEY[s]) return STOCK_TO_UPSTOX_KEY[s];
  return null;
}

/**
 * Batch lookup: convert an array of symbols to Upstox instrument_keys.
 */
export function getUpstoxKeys(symbols: string[]): string[] {
  const out: string[] = [];
  for (const s of symbols) {
    const k = getUpstoxKey(s);
    if (k) out.push(k);
  }
  return out;
}
